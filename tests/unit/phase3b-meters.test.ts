import { test } from 'node:test';
import assert from 'node:assert/strict';
import { actorIdFor } from '../../src/identity.ts';
import { normalizeStory } from '../../src/story.ts';
import { packById, registerLocalPacks } from '../../src/pack/packs.ts';
import { meterFacts } from '../../src/pipeline/character-state.ts';
import { choice, harness, scriptJudge, writerReplies } from './support/test-host.ts';
import type { Answer } from '../../src/types.ts';

test('3b/14: missing meter answers remain unassessed across persistence and receive a free first judgment', async () => {
  const { controller, host } = await harness();
  controller.settings.modules = { speaker: false, decisions: false, meters: true, secrets: false, lore: false };
  controller.settings.reactions.enabled = false;
  await controller.setChatPack('romance');
  writerReplies(host, controller, 'Guide', 'guide.png', 'The guide listens.');
  scriptJudge(controller, { meter_1_nerve: choice('steady'), meter_1_regard: choice('invalid') });
  host.composerValue = 'We speak by the gate.';
  await controller.directorSend();
  const first = Object.values(controller.record!.attempts).at(-1)!;
  const npc = actorIdFor('Guide', 'guide.png');
  assert.deepEqual(first.storyAfter!.assessed![npc], { regard: false, nerve: true });
  assert.doesNotMatch(first.frozenStateBlock!, /regard/);
  assert.equal(controller.characterStateForUi()[0]!.meters[0]!.level, 'not yet judged');
  assert.deepEqual(meterFacts(packById('romance'), first.storyAfter!.meters, 'Player', first.storyAfter!.assessed)[npc], { nerve: 'steady (3 of 5)' });
  controller.record!.story = normalizeStory(JSON.parse(JSON.stringify(controller.record!.story)));
  const requests = scriptJudge(controller, { meter_1_regard: choice('smitten'), meter_1_nerve: choice('relentless') });
  host.composerValue = 'We continue the conversation.';
  await controller.directorSend();
  const questions = requests.find(request => 'meter_1_regard' in request.questions)!.questions;
  assert.deepEqual(Object.keys(questions.meter_1_regard!.criteria!), ['cold', 'guarded', 'friendly', 'warm', 'smitten']);
  assert.deepEqual(Object.keys(questions.meter_1_nerve!.criteria!), ['hesitant', 'steady', 'bold']);
  const next = Object.values(controller.record!.attempts).at(-1)!;
  assert.deepEqual(next.storyAfter!.meters[npc], { regard: 4, nerve: 2 });
  assert.deepEqual(next.storyAfter!.assessed![npc], { regard: true, nerve: true });
});

test('3b/14: six characters with three meters and a reveal use capped batches without starving tail questions', async () => {
  const pack = structuredClone(packById('romance'));
  pack.id = 'meter_batch_fixture';
  pack.meters.push({ key: 'focus', label: 'focus', about: 'How focused the character is.', initial: 0, levels: ['absent', 'distracted', 'present', 'focused', 'intent'] });
  assert.deepEqual(registerLocalPacks({ schemaVersion: 1, packs: [pack] }).loaded, [pack.id]);
  const { controller, host } = await harness({ group: true });
  const cast = Array.from({ length: 6 }, (_, i) => ({ name: `Guide ${i + 1}`, avatar: `guide-${i + 1}.png`, description: `Character ${i + 1}.` }));
  host.context.characters = cast;
  host.context.groups![0]!.members = cast.map(character => character.avatar);
  controller.settings.modules = { speaker: false, decisions: false, meters: true, secrets: true, lore: false };
  controller.settings.reactions.enabled = false;
  await controller.setChatPack(pack.id);
  controller.record!.story.secrets = [{ id: 'secret', text: 'The spare key is by the gate.', holders: [] }];
  const answers: Record<string, Answer> = { reveal_1: choice('EVERYONE') };
  for (let n = 1; n <= 6; n++) Object.assign(answers, { [`meter_${n}_regard`]: choice('smitten'), [`meter_${n}_nerve`]: choice('relentless'), [`meter_${n}_focus`]: choice('intent') });
  writerReplies(host, controller, cast[0]!.name, cast[0]!.avatar, 'The guides listen.');
  const requests = scriptJudge(controller, answers);
  host.composerValue = 'I explain where the key is.';
  await controller.directorSend();
  assert.deepEqual(requests.map(request => Object.keys(request.questions).length), [16, 3]);
  const attempt = Object.values(controller.record!.attempts).at(-1)!;
  const last = actorIdFor(cast[5]!.name, cast[5]!.avatar);
  assert.deepEqual(attempt.storyAfter!.meters[last], { regard: 4, nerve: 4, focus: 4 });
  assert.deepEqual(attempt.storyAfter!.assessed![last], { regard: true, nerve: true, focus: true });
  assert.equal(attempt.storyAfter!.knownBy.secret!.length, 7);
  const next = scriptJudge(controller, answers);
  host.composerValue = 'We consider the explanation.';
  await controller.directorSend();
  assert.deepEqual(next.map(request => Object.keys(request.questions).length), [16, 2]);
  assert.deepEqual(Object.keys(next[1]!.questions.meter_6_focus!.criteria!), ['focused', 'intent']);
});
